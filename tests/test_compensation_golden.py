def assert_close(actual: float, expected: float, tol: float = 0.01, label: str = "") -> None:
    """Strict finite-number comparison: explicitly rejects NaN, +Inf, -Inf, and bool."""
    if isinstance(actual, bool) or not isinstance(actual, (int, float)):
        raise AssertionError(f"[FAIL] {label}: non-numeric actual={actual!r}")
    if isinstance(expected, bool) or not isinstance(expected, (int, float)):
        raise AssertionError(f"[FAIL] {label}: non-numeric expected={expected!r}")
    if not math.isfinite(actual):
        raise AssertionError(f"[FAIL] {label}: non-finite actual={actual!r}")
    if not math.isfinite(expected):
        raise AssertionError(f"[FAIL] {label}: non-finite expected={expected!r}")
    if not (abs(actual - expected) <= tol):
        raise AssertionError(f"[FAIL] {label}: actual={actual}, expected={expected} (tol={tol})")


